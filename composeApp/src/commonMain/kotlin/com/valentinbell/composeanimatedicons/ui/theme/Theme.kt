@Composable
fun AppTheme(
    isDarkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (isDarkTheme) DarkColorScheme else LightColorScheme

    val selectedFont = if (customAppLocale == "th") {
        getThaiFontFamily()
    } else {
        FontFamily.Default
    }

    CompositionLocalProvider(
        LocalThemeState provides ThemeState(isDarkTheme)
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = appTypography(selectedFont),
            content = content
        )
    }
}

data class ThemeState(val isDarkTheme: Boolean)

val LocalThemeState = staticCompositionLocalOf { ThemeState(isDarkTheme = false) }
